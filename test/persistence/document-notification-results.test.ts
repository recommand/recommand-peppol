import { beforeEach, describe, expect, it, mock } from "bun:test";

// The notification senders are exercised against fakes of the address store, the
// attachment builder and the mail service, so the per-address outcome can be asserted
// without a database or Postmark.

const addresses = [
  { email: "accounting@example.com", includeAutoGeneratedPdfIncoming: false, includeDocumentJsonIncoming: false },
  { email: "owner@example.com", includeAutoGeneratedPdfIncoming: false, includeDocumentJsonIncoming: false },
];
const sent: string[] = [];
const alerts: string[] = [];
let failFor: string | null = null;
let failBuildingAttachments = false;

mock.module("@peppol/data/company-notification-emails", () => ({
  getIncomingCompanyNotificationEmailAddresses: async () => addresses,
  getOutgoingCompanyNotificationEmailAddresses: async () => addresses,
}));
mock.module("@peppol/data/email/document-notification-props", () => ({
  buildIncomingDocumentNotificationAttachmentParts: async () => {
    if (failBuildingAttachments) throw new Error("attachments unavailable");
    return { embeddedAttachments: [], xmlAttachment: null, autoGeneratedPdfAttachment: null, documentJsonAttachment: null };
  },
  buildOutgoingDocumentNotificationAttachmentParts: async () => ({
    embeddedAttachments: [], xmlAttachment: null, autoGeneratedPdfAttachment: null, documentJsonAttachment: null,
  }),
}));
mock.module("@peppol/data/notification-language", () => ({
  getCompanyNotificationT: async () =>
    (strings: TemplateStringsArray | string, ...values: unknown[]) =>
      typeof strings === "string" ? strings : strings.reduce((text, part, index) => text + part + (values[index] ?? ""), ""),
}));
mock.module("@core/lib/email", () => ({
  sendEmail: async ({ to }: { to: string }) => {
    if (to === failFor) throw new Error("render failed");
    sent.push(to);
    return { success: true, messageId: `msg-${to}` };
  },
}));
mock.module("@peppol/utils/system-notifications/telegram", () => ({
  sendSystemAlert: async (_title: string, message: string) => {
    alerts.push(message);
  },
}));

const { sendIncomingDocumentNotifications, sendOutgoingDocumentNotifications } =
  await import("../../data/send-document-notifications");

const options = {
  companyId: "c-a",
  companyName: "Acme",
  type: "invoice" as const,
  parsedDocument: null,
  transmittedDocumentId: "doc-a",
};

describe("document notification results", () => {
  beforeEach(() => {
    sent.length = 0;
    alerts.length = 0;
    failFor = null;
    failBuildingAttachments = false;
  });

  it("reports each address, and a failed one does not stop the others", async () => {
    failFor = "accounting@example.com";
    const results = await sendIncomingDocumentNotifications({ ...options, xmlDocument: "<Invoice/>" });
    expect(results).toEqual([
      { email: "accounting@example.com", sent: false, error: "render failed" },
      { email: "owner@example.com", sent: true },
    ]);
    expect(sent).toEqual(["owner@example.com"]);
    expect(alerts).toEqual(["Failed to send incoming document notification to accounting@example.com."]);
  });

  it("notifies only the requested configured addresses, compared without case", async () => {
    const results = await sendOutgoingDocumentNotifications({
      ...options,
      xmlDocument: null,
      onlyEmails: [" Owner@Example.com ", "stranger@example.com"],
    });
    expect(results).toEqual([{ email: "owner@example.com", sent: true }]);
    expect(sent).toEqual(["owner@example.com"]);
  });

  it("throws a failure that happens before any address is tried", async () => {
    failBuildingAttachments = true;
    await expect(sendIncomingDocumentNotifications({ ...options, xmlDocument: "<Invoice/>" }))
      .rejects.toThrow("attachments unavailable");
    expect(sent).toEqual([]);
  });
});
